function NetworkBg() {
  const ref = useRef(null);
  useEffect(() => {
    const canvas = ref.current;
    if (!canvas) return undefined;
    const ctx = canvas.getContext("2d");
    const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    let w = 0, h = 0, raf = 0, dots = [];
    const mouse = { x: -9999, y: -9999 };
    function resize() {
      const dpr = Math.min(window.devicePixelRatio || 1, 2);
      w = window.innerWidth; h = window.innerHeight;
      canvas.width = w * dpr; canvas.height = h * dpr;
      canvas.style.width = w + "px"; canvas.style.height = h + "px";
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      const n = Math.max(40, Math.min(110, Math.round((w * h) / 16000)));
      dots = Array.from({ length: n }, () => ({
        x: Math.random() * w, y: Math.random() * h,
        vx: (Math.random() - 0.5) * 0.35, vy: (Math.random() - 0.5) * 0.35,
        r: Math.random() * 1.6 + 0.7, tw: Math.random() * 6.28,
      }));
    }
    function frame() {
      ctx.clearRect(0, 0, w, h);
      for (const d of dots) {
        if (!reduce) { d.x += d.vx; d.y += d.vy; d.tw += 0.03; }
        if (d.x < 0 || d.x > w) d.vx *= -1;
        if (d.y < 0 || d.y > h) d.vy *= -1;
      }
      for (let i = 0; i < dots.length; i++) {
        const a = dots[i];
        for (let j = i + 1; j < dots.length; j++) {
          const b = dots[j];
          const dist = Math.hypot(a.x - b.x, a.y - b.y);
          if (dist < 150) {
            ctx.strokeStyle = `rgba(210, 236, 255, ${0.34 * (1 - dist / 150)})`;
            ctx.lineWidth = 1;
            ctx.beginPath(); ctx.moveTo(a.x, a.y); ctx.lineTo(b.x, b.y); ctx.stroke();
          }
        }
        const md = Math.hypot(a.x - mouse.x, a.y - mouse.y);
        if (md < 190) {
          ctx.strokeStyle = `rgba(255, 255, 255, ${0.7 * (1 - md / 190)})`;
          ctx.beginPath(); ctx.moveTo(a.x, a.y); ctx.lineTo(mouse.x, mouse.y); ctx.stroke();
        }
        const glow = 0.55 + 0.45 * Math.sin(a.tw);
        ctx.fillStyle = `rgba(235, 247, 255, ${0.55 + 0.45 * glow})`;
        ctx.shadowColor = "rgba(140, 210, 255, 0.95)"; ctx.shadowBlur = 8 * glow;
        ctx.beginPath(); ctx.arc(a.x, a.y, a.r, 0, 6.283); ctx.fill();
        ctx.shadowBlur = 0;
      }
      raf = requestAnimationFrame(frame);
    }
    const move = (e) => { mouse.x = e.clientX; mouse.y = e.clientY; };
    const leave = () => { mouse.x = -9999; mouse.y = -9999; };
    resize(); frame();
    window.addEventListener("resize", resize);
    window.addEventListener("mousemove", move);
    window.addEventListener("mouseleave", leave);
    return () => {
      cancelAnimationFrame(raf);
      window.removeEventListener("resize", resize);
      window.removeEventListener("mousemove", move);
      window.removeEventListener("mouseleave", leave);
    };
  }, []);
  return <canvas ref={ref} className="netbg" aria-hidden="true" />;
}

export default function App() {
  const { status, meta } = useApiStatus();
  const [lang, setLang] = useState("auto");
  const [tab, setTab] = useState("ask");
  const [messages, setMessages] = useState([]);
  const [input, setInput] = useState("");
  const [plain, setPlain] = useState(false);
  const [loading, setLoading] = useState(false);
  const [printId, setPrintId] = useState(null);
  const endRef = useRef(null);
  const t = T[lang === "bn" ? "bn" : "en"];

  useEffect(() => {
    endRef.current?.scrollIntoView({ behavior: "smooth", block: "end" });
  }, [messages, loading]);

  useEffect(() => {
    const clear = () => setPrintId(null);
    window.addEventListener("afterprint", clear);
    return () => window.removeEventListener("afterprint", clear);
  }, []);

  async function send(text) {
    const question = text.trim();
    setTab("ask");
    if (question.length < 2 || loading) return;
    setMessages((prev) => [...prev, { role: "user", text: question }]);
    setInput("");
    setLoading(true);
    try {
      const res = await fetch(`${API}/api/chat`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ message: question, plain_mode: plain, language: lang }),
      });
      if (!res.ok) {
        let detail = "";
        try { detail = (await res.json()).detail || ""; } catch { /* no JSON body */ }
        const failure = new Error(typeof detail === "string" ? detail : "");
        failure.fromServer = true;
        throw failure;
      }
      const data = await res.json();
      setMessages((prev) => [...prev, {
        role: "bot", text: data.answer, sources: data.sources, trace: data.trace,
        confident: data.confident, language: data.language, topScore: data.top_score,
      }]);
    } catch (err) {
      setMessages((prev) => [...prev, {
        role: "bot", error: true,
        text: err.fromServer && err.message ? err.message : t.failure,
      }]);
    } finally {
      setLoading(false);
    }
  }

  function printMessage(index) {
    setPrintId(index);
    setTimeout(() => window.print(), 60);
  }

  return (
    <div className="app">
      <div className="aurora" aria-hidden="true"><i /><i /><i /></div>
      <NetworkBg />

      <header className="topbar">
        <div className="brand">
          <div className="logo"><span>E</span></div>
          <div>
            <div className="brand-name">ESBC-AI</div>
            <div className="brand-sub">{t.tagline}</div>
          </div>
        </div>
        <div className="top-actions">
          <div className="seg-wrap">
            <span className="seg-caption">{t.langLabel}</span>
            <div className="seg" role="group" aria-label={t.langLabel}>
              {[["auto", t.auto], ["en", "English"], ["bn", "বাংলা"]].map(([id, label]) => (
                <button key={id} className={lang === id ? "on" : ""} onClick={() => setLang(id)}>{label}</button>
              ))}
            </div>
          </div>
          <label className="toggle" title={t.simpleHint}>
            <input type="checkbox" checked={plain} onChange={(e) => setPlain(e.target.checked)} />
            <span className="track"><span className="thumb" /></span>
            <span className="toggle-label">{t.simple}</span>
          </label>
          <span className={`status ${status}`}><i />{t.status[status]}</span>
        </div>
      </header>

      <nav className="tabs" aria-label="Modes">
        {Object.entries(t.tabs).map(([id, label]) => (
          <button key={id} className={tab === id ? "tab active" : "tab"} onClick={() => setTab(id)}>{label}</button>
        ))}
      </nav>

      <main className="content">
        {tab === "death" && <DeathGuide t={t} onSubmit={send} />}
        {tab === "benefit" && <BenefitFinder t={t} onSubmit={send} />}

        {tab === "ask" && messages.length === 0 && (
          <>
            <section className="hero">
              <div className="hero-text">
              <span className="eyebrow">{t.eyebrow}</span>
              <h1>{t.titleA} <span className="grad">{t.titleB}</span></h1>
              <p>{t.lead}</p>
              {meta?.ready && (
                <div className="stats">
                  <div><b>{meta.documents}</b><span>{t.pages}</span></div>
                  <div><b>{meta.services.length}</b><span>{t.areas}</span></div>
                  <div><b>{meta.last_checked}</b><span>{t.verified}</span></div>
                </div>
              )}
              </div>
              <div className="art">
                <img src="/banner.jpg" alt="ESBC AI: the National Martyrs' Memorial and Parliament House across the water" />
                <div className="art-badges">{t.badges.map((b) => <span key={b}>{b}</span>)}</div>
              </div>
            </section>

            <section className="tiles-wrap">
              <h2 className="tiles-title">{t.tilesTitle}</h2>
              <div className="tiles">
                {t.tiles.map(([icon, name, question]) => (
                  <button key={icon} className="tile" onClick={() => send(question)}>
                    <span className="tile-icon"><Icon name={icon} /></span>
                    <span className="tile-name">{name}</span>
                    <span className="tile-q">{question}</span>
                  </button>
                ))}
              </div>
            </section>
          </>
        )}

        {tab === "ask" && messages.map((m, i) =>
          m.role === "user" ? (
            <div key={i} className="row user"><div className="bubble user">{m.text}</div></div>
          ) : (
            <div key={i} className={`row bot ${printId === i ? "print-target" : ""}`}>
              <div className="avatar">E</div>
              <div className="bubble bot">
                <BotMessage m={m} t={t} onPrint={() => printMessage(i)} />
                <div className="print-note">{t.printNote}</div>
              </div>
            </div>
          )
        )}

        {tab === "ask" && loading && (
          <div className="row bot">
            <div className="avatar">E</div>
            <div className="bubble bot">
              <div className="typing"><i /><i /><i /></div>
              <div className="waiting">{t.waiting}</div>
            </div>
          </div>
        )}
        <div ref={endRef} />
      </main>

      {(
        <footer className="composer-wrap">
          <form className="composer" onSubmit={(e) => { e.preventDefault(); send(input); }}>
            <input
              value={input}
              onChange={(e) => setInput(e.target.value)}
              placeholder={t.placeholder}
              maxLength={1000}
              aria-label={t.placeholder}
            />
            <button type="submit" disabled={loading || input.trim().length < 2}>{t.send}</button>
          </form>
          <div className="hint">{t.hints[lang]}</div>
        </footer>
      )}

      <div className="credit">
        {t.footer1}
        <br />
        {t.footer2}
      </div>
    </div>
  );
}
